import { mkdirSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import { serializeStoryConfig } from "@/lib/config-io";
import type { StoryConfig } from "@/types/story-config";
import type { BeatPlan } from "@/types/beat-plan";

/**
 * v0.3.0 输出（§35）：每次生成保存四件套 ——
 *   <stamp>_story.md            正文（含 metadata 引用块）
 *   <stamp>_story.config.json   当时使用的 StoryConfig 快照（可追溯性）
 *   <stamp>_story.beats.json    当时使用的 BeatPlan 快照（§34 JSON 序列化）
 *   <stamp>_story.meta.json     基本元数据（§36：含 beat_count，禁 run_id/review_score）
 * 文件名不含用户输入（服务端时间戳 + 固定后缀）。仍不是 ArtifactStore（§37）。
 */
export interface StoryRunMeta {
  project_version: string;
  model: string;
  generated_at: string;
  config_file?: string;
  beats_file?: string;
  beat_count?: number;
}

export async function saveStoryWithSnapshot(
  config: StoryConfig,
  plan: BeatPlan,
  content: string,
  meta: Omit<StoryRunMeta, "config_file" | "beats_file" | "beat_count">,
): Promise<{ mdPath: string; configPath: string; beatsPath: string; metaPath: string }> {
  const dir = join(process.cwd(), "outputs");
  mkdirSync(dir, { recursive: true });
  const now = new Date();
  const pad = (n: number) => String(n).padStart(2, "0");
  const stamp = `${now.getFullYear()}${pad(now.getMonth() + 1)}${pad(now.getDate())}_${pad(now.getHours())}${pad(now.getMinutes())}${pad(now.getSeconds())}`;

  const mdPath = join(dir, `${stamp}_story.md`);
  const md = `# ${config.title}

> Genre: ${config.genre}  
> Target Words: ${config.target_words}  
> Beats: ${plan.beats.length}${config.style ? `  \n> Style: ${config.style}` : ""}

${content}

---
Generated by Short Story Generator v0.3.0
`;
  await writeFile(mdPath, md, "utf8");

  const configPath = join(dir, `${stamp}_story.config.json`);
  await writeFile(configPath, serializeStoryConfig(config), "utf8");

  const beatsPath = join(dir, `${stamp}_story.beats.json`);
  await writeFile(beatsPath, JSON.stringify(plan, null, 2), "utf8");

  const metaPath = join(dir, `${stamp}_story.meta.json`);
  const fullMeta: StoryRunMeta = {
    ...meta,
    config_file: configPath,
    beats_file: beatsPath,
    beat_count: plan.beats.length,
  };
  await writeFile(metaPath, JSON.stringify(fullMeta, null, 2), "utf8");

  return { mdPath, configPath, beatsPath, metaPath };
}
